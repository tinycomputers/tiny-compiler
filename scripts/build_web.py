#!/usr/bin/env python3
"""Assemble everything the browser needs into web/ (run automatically by npm predev/prebuild).

web/public/py/bundle.json          the Python sources (tinyc, runtime, tinygpu) for Pyodide
web/public/tiny_tpu.{mjs,wasm}     the tiny-tpu WASM build from the pinned submodule
web/public/runtime/ttpu-exec.mjs   the one tiny-tpu executor, shared with Node
web/src/lib/examples.generated.ts  the example programs, so the UI cannot drift from examples/
"""

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
PKGS = {
    "tinyc": ROOT / "tinyc",
    "runtime": ROOT / "runtime",
    "tinygpu": ROOT / "targets" / "tiny-gpu" / "src" / "tinygpu",
}
ONLY_RUNTIME = {"__init__.py", "gpu_runner.py", "web_api.py"}  # the rest of runtime/ is Node/CLI


def bundle() -> dict:
    files = {}
    for pkg, root in PKGS.items():
        for path in sorted(root.rglob("*.py")):
            if "__pycache__" in path.parts or path.name == "__main__.py":
                continue
            if pkg == "runtime" and path.name not in ONLY_RUNTIME:
                continue
            rel = f"{pkg}/{path.relative_to(root).as_posix()}"
            files[rel] = path.read_text()
    return {"files": files}


def main() -> None:
    out_py = WEB / "public" / "py"
    out_py.mkdir(parents=True, exist_ok=True)
    data = bundle()
    (out_py / "bundle.json").write_text(json.dumps(data))
    print(f"bundle.json: {len(data['files'])} python files")

    tpu_public = ROOT / "targets" / "tiny-tpu" / "web" / "public"
    for name in ("tiny_tpu.mjs", "tiny_tpu.wasm"):
        shutil.copyfile(tpu_public / name, WEB / "public" / name)
    shutil.copyfile(
        ROOT / "runtime" / "ttpu-exec.mjs", WEB / "public" / "runtime" / "ttpu-exec.mjs"
    )

    examples = {p.stem: p.read_text() for p in sorted((ROOT / "examples").glob("*.tiny"))}
    (WEB / "src" / "lib" / "examples.generated.ts").write_text(
        "// Generated by scripts/build_web.py from examples/. Do not edit.\n"
        f"export const EXAMPLES: Record<string, string> = {json.dumps(examples, indent=2)};\n"
    )
    print(f"examples: {', '.join(examples)}")


if __name__ == "__main__":
    main()
